/* ============================================================================
   lead-hold.js: HOLD-THEN-ASSIGN for new leads, and the PM's OWN lead rule (patch LEADHOLD)

   Owner (10/28): "before assigning automatically, give for the rest of the work day for admin to approve or assign
   to someone else, then automatically goes to who is assigned. Remember any jobs initiated from GrayCo Photos for a
   PM is considered their own lead, paid under a different structure."
   Owner adds: "if a PM enters the job in New Project first, that also counts … when we get it (company channels)
   it's ours" · "ALL RoofScout leads are GrayCo leads, and anything generated by the CRM or marketing is too."

   1. HOLD. When the CRM's lead routing (lead roles / Senior Estimator) picks a person for a NEW lead, the lead is not
      assigned yet: it carries  hold = { state: 'held', name, email, field, label, k, until, at }  and shows
      "Suggested: <name> — assigns at 5:00 PM". The work day ends 5:00 PM Central, Monday–Friday; a lead that comes in
      after 5 PM or on a weekend is held until 5:00 PM the next work day. During the hold an admin approves the
      suggestion or picks someone else (assigns now); nobody acts → at the deadline it goes to the suggested person
      (the 10-minute bid-alerts run on the server, so no browser has to be open) and they get the normal notice.
      NOT held: emergencies / mitigation (water, fire, flood, smoke, mold, "EMERGENCY"), a bid due before the hold
      ends (or the next day), a lead an admin made or assigned by hand (holdSkip), a PM's own lead.
   2. OWN LEAD. A lead / job a PM (any staff who is not admin / office) enters by hand, or one started from their own
      GrayCo Photos (CompanyCam) project, is THAT PM's own lead: assigned to them at once, never held, and tagged
      (commissionSource 'self', leadIsMine, ownLead, leadOwner …) so the pay uses their own-lead structure. Company
      channels and RoofScout / marketing always win (GrayCo lead), and so does an earlier company lead at the same
      address ("first in wins"). An admin's own choice (leadSourceOverride) is never changed.
   Pure: no I/O. The server (bid-inbox.js, bid-alerts.js) requires it; the CRM page carries the same file word for word.
   ========================================================================== */
(function(root){
'use strict';
function s(v){ return v == null ? '' : String(v).trim(); }
function low(v){ return s(v).toLowerCase(); }
function arr(v){ return Array.isArray(v) ? v : []; }

var TZ = 'America/Chicago', END_H = 17, END_M = 0;
var DOW = { Sun: 0, Mon: 1, Tue: 2, Wed: 3, Thu: 4, Fri: 5, Sat: 6 };
/* the wall clock in Central time: { y, mo, d, h, mi, dow } */
function ct(ms){
  var o = {};
  try {
    new Intl.DateTimeFormat('en-US', { timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', weekday: 'short', hourCycle: 'h23' })
      .formatToParts(new Date(ms)).forEach(function(p){ o[p.type] = p.value; });
  } catch (e) { var d = new Date(ms - 6 * 3600e3); return { y: d.getUTCFullYear(), mo: d.getUTCMonth() + 1, d: d.getUTCDate(), h: d.getUTCHours(), mi: d.getUTCMinutes(), dow: d.getUTCDay() }; }
  return { y: +o.year, mo: +o.month, d: +o.day, h: (+o.hour) % 24, mi: +o.minute, dow: DOW[o.weekday] };
}
/* Central wall time → epoch ms (daylight saving or not) */
function ctMs(y, mo, d, h, mi){
  var guess = Date.UTC(y, mo - 1, d, h, mi);
  for (var i = 0; i < 2; i++) { var w = ct(guess); guess += Date.UTC(y, mo - 1, d, h, mi) - Date.UTC(w.y, w.mo - 1, w.d, w.h, w.mi); }
  return guess;
}
/* when a lead that came in at `now` stops being held: 5:00 PM Central today (a work day, before 5), else the next work day */
function holdUntil(now){
  var t = typeof now === 'number' ? now : Date.now(), w = ct(t), k = 0;
  var workday = function(dow){ return dow >= 1 && dow <= 5; };
  if (!(workday(w.dow) && w.h * 60 + w.mi < END_H * 60 + END_M)) {
    k = 1; while (!workday((w.dow + k) % 7)) k++;
  }
  var day = new Date(Date.UTC(w.y, w.mo - 1, w.d + k));
  return new Date(ctMs(day.getUTCFullYear(), day.getUTCMonth() + 1, day.getUTCDate(), END_H, END_M)).toISOString();
}
/* "5:00 PM today" / "5:00 PM Mon 11/2" (as seen from `now`) */
function whenLabel(iso, now){
  var t = Date.parse(iso); if (!isFinite(t)) return '5:00 PM';
  var a = ct(t), b = ct(typeof now === 'number' ? now : Date.now());
  var hh = a.h % 12 || 12, tm = hh + ':' + ('0' + a.mi).slice(-2) + ' ' + (a.h < 12 ? 'AM' : 'PM');
  if (a.y === b.y && a.mo === b.mo && a.d === b.d) return tm + ' today';
  return tm + ' ' + ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'][a.dow] + ' ' + a.mo + '/' + a.d;
}

/* ── what is never held ── */
var EMERG = /\b(emergenc\w*|water|flood\w*|fire|smoke|soot|mitigation|mou?ld|leak\w*|burst|sewage|dry[\s-]*out|asap|urgent)\b/i;
function textOf(l){
  var c = l && l.contact && typeof l.contact === 'object' ? l.contact : {}, x = (l && l.leadExtra) || {};
  return [l.type, l.leadKind, l.jobType, l.title, l.name, l.detail, l.websiteForm, l.form, l.service, l.subject, l.message, l.scope, l.urgency, l.causeOfLoss, c.message, x.message, x.websiteForm, x.urgency]
    .concat(arr(l.notes).slice(0, 4)).map(s).join(' | ');
}
function isEmergency(l){
  if (!l) return false;
  if (l.emergency === true || l.isEmergency === true || (l.leadExtra && l.leadExtra.emergency === true) || /^emergency$/i.test(s(l.urgency))) return true;
  if (/commercial|government|bid/i.test(s(l.type || l.leadKind)) && !/emergenc/i.test(s(l.title) + ' ' + s(l.name))) return false;   /* a bid that mentions water is not an emergency */
  return EMERG.test(textOf(l));
}
function dueSoon(l, until){
  var d = s(l && l.bidDue).slice(0, 10); if (!/^\d{4}-\d{2}-\d{2}$/.test(d)) return false;
  var u = Date.parse(until); if (!isFinite(u)) return false;
  return Date.parse(d + 'T00:00:00Z') <= u + 86400e3;   /* due by the day after the hold ends: the estimator needs it now */
}
/* the lead's person, if any */
function assignee(l){ return s(l && (l.pm || l.estimator || l.apm)); }
function isHeld(l){ return !!(l && l.hold && l.hold.state === 'held' && s(l.hold.name) && !assignee(l)); }
function isDue(l, now){ return isHeld(l) && Date.parse(l.hold.until) <= (typeof now === 'number' ? now : Date.now()); }

/* ── GrayCo lead or the PM's own? ── */
/* company channels, RoofScout and anything the CRM / marketing made — these always win */
var COMPANY = /roof ?scout|website|web ?form|marketing|campaign|news ?letter|referr|win-?back|maint(enance)? ?plan|review|social|facebook|instagram|nextdoor|google|\bads?\b|\bppc\b|\blsa\b|local services|\/go\/|tracked|door ?hanger|postcard|flyer|print ?pack|\bqr\b|partner|estimate|renewal|lead ?inbox|leads@|bids@|claims@|office@|missed call|phone call|\bphone\b|call ?rail|roof ?ignite|contractor connection|alacrity|sedgwick|home ?advisor|angi|thumbtack|bid ?board|building ?connected|planhub|plan ?room|sam\.gov|giveaway|event|coupon|grayco lead|text us|voicemail/i;
function companyWhy(r){
  if (!r) return '';
  if (r.rsLeadId || /^LEAD_RS_/.test(s(r.id)) || /roof ?scout/i.test([r.source, r.leadSource, r.origin, r.createdVia].map(s).join(' '))) return 'a RoofScout lead (always GrayCo’s)';
  if (r.inboxId || r.leadInboxId || r.websiteLead || r.grayCoLead === true || r.partnerCode || r.partnerId || r.attrib || r.trackCode || r.utmCampaign || r.mkSource || r.campaignId || r.winbackId || r.maintPlanId || r.renewalOf || r.fromEstimateId || r.intakeId)
    return 'came in through a company channel';
  if (/^(website|api|watch|email|partner|partner-bid|referral|phone|missed-call|sms|voice|marketing)$/i.test(s(r.origin))) return 'came in through ' + s(r.origin);
  var src = [r.source, r.leadSource, r.sourceKind, r.howHeard, r.mkSource, r.origin].map(s).filter(function(v){ return v && !/^(grayco|self|self-generated.*|companycam|crm|manual|desk|field)$/i.test(v); }).join(' ');
  if (COMPANY.test(src)) return 'GrayCo lead (' + src.slice(0, 60) + ')';
  return '';
}
function ccWhy(r){
  if (!r || r.ccLinkedBy) return '';
  if (/^(PRJcc_|LCC_|LCCR_|LGN_)/.test(s(r.id)) || r._ccAuto || r._ccServer || low(r.source) === 'companycam' || ((r.ccamId || r.ccProjectId) && !r.inboxId)) return 'started from a GrayCo Photos project';
  return '';
}
/* a person on the team list: 'admin' (owner / admin / office) or 'pm' (anyone else who works leads) */
function personKind(u){
  if (!u) return '';
  var roles = u.roles || {}, x = low([u.role, u.profile, u.title].map(s).join(' '));
  if (low(u.payType) === 'owner' || roles.admin || roles.office || /\b(admin|owner|office)\b/.test(x)) return 'admin';
  return 'pm';
}
function normAddr(a){
  var line = low(a).split(',')[0].replace(/[.#]/g, ' ').replace(/[^a-z0-9 ]/g, ' ').replace(/\s+/g, ' ').trim();
  if (!line || !/\d/.test(line)) return '';
  var SUF = { street: 'st', road: 'rd', avenue: 'ave', av: 'ave', drive: 'dr', lane: 'ln', court: 'ct', boulevard: 'blvd', highway: 'hwy', place: 'pl', circle: 'cir', parkway: 'pkwy', cove: 'cv', terrace: 'ter', trail: 'trl', north: 'n', south: 's', east: 'e', west: 'w' };
  return line.split(' ').map(function(w){ return SUF[w] || w; }).join('');
}
function bornMs(r){
  var c = [r && r.createdAt, r && r.receivedAt, r && r.created, r && r.dateAdded].map(function(v){ var t = typeof v === 'number' ? v : Date.parse(s(v)); return isFinite(t) && t > 0 ? t : 0; }).filter(Boolean);
  return c.length ? Math.min.apply(null, c) : 0;
}
function storedSource(r){
  var cs = low(r && r.commissionSource);
  if (cs === 'self') return 'self'; if (cs === 'company' || cs === 'grayco') return 'company';
  if (r && (r.graycoOrigin === true || r.assignedByAdmin === true)) return 'company';
  if (r && (r.ownLead === true || r.leadIsMine === true || r.pmSourced === true)) return 'self';
  return '';
}
/* an earlier GrayCo (company) record at the same street address: "when we get it, it's ours" (first in wins) */
function earlierCompany(r, others){
  var a = normAddr(r && (r.address || r.jobAddress)); if (a.length < 6) return null;
  var at = bornMs(r) || Date.now(), best = null;
  arr(others).forEach(function(o){
    if (!o || s(o.id) === s(r.id) || o.deleted || o._deleted) return;
    if (normAddr(o.address || o.jobAddress) !== a) return;
    var t = bornMs(o); if (!t || t >= at - 60000) return;
    var company = !!companyWhy(o) || storedSource(o) === 'company';
    if (!company) return;
    if (!best || t < best.t) best = { t: t, id: s(o.id), name: s(o.name || o.title || o.company) };
  });
  return best;
}
/* → { source: 'self', pm, why } | { source: 'company', why } | null (leave it: an admin's choice, or nothing to go on)
   ctx: { creator: { name, email, kind }, ccPm: '<the GrayCo Photos creator's PM>', others: [leads / jobs / inbox items] } */
function decideSource(r, ctx){
  ctx = ctx || {};
  if (!r || (r.leadSourceOverride && r.leadSourceOverride.source) || r.ownLeadSetBy) return null;
  var cw = companyWhy(r); if (cw) return { source: 'company', why: 'GrayCo lead — ' + cw };
  var pm = '', why = '';
  if (ccWhy(r)) { pm = s(ctx.ccPm); if (!pm) return { source: 'company', why: 'GrayCo lead — a GrayCo Photos project with no PM of its own' }; why = 'started from ' + pm + '’s GrayCo Photos project'; }
  else if (ctx.creator && ctx.creator.kind === 'pm' && s(ctx.creator.name)) { pm = s(ctx.creator.name); why = 'entered by hand by ' + pm; }
  else if (ctx.creator && ctx.creator.kind === 'admin') return { source: 'company', why: 'GrayCo lead — entered by the office / an admin' + (ctx.creator.name ? ' (' + s(ctx.creator.name) + ')' : '') };
  else return null;
  var e = earlierCompany(r, ctx.others);
  if (e) return { source: 'company', why: 'GrayCo lead — "' + (e.name || e.id) + '" was already in the CRM at that address (first in wins)', evidence: e };
  return { source: 'self', pm: pm, why: pm + '’s own lead — ' + why };
}
function ownFields(pm, why, at){
  var label = 'Self-generated (' + pm + ')';
  return { commissionSource: 'self', pmSourced: true, selfGenerated: true, leadIsMine: true, ownLead: true, graycoOrigin: false, broughtInBy: pm, leadOwner: pm,
    leadSource: label, leadSourceTag: 'PM’s own lead', leadSourceWhy: s(why), leadSourceAt: at || new Date().toISOString(), leadSourceV: 1 };
}
function companyFields(why, at){
  return { commissionSource: 'company', pmSourced: false, selfGenerated: false, leadIsMine: false, ownLead: false, graycoOrigin: true, leadSourceTag: 'GrayCo lead',
    leadSourceWhy: s(why), leadSourceAt: at || new Date().toISOString(), leadSourceV: 1 };
}

/* ── the hold itself ── */
/* should a new lead the routing gave to `pick` ({ field, name, email, label, k }) be held? → '' | why not */
function noHoldWhy(l, now){
  if (!l) return 'no lead';
  if (l.holdSkip) return 'made or assigned by an admin';
  if (l.hold && l.hold.state) return 'already handled';
  if (ccWhy(l) || storedSource(l) === 'self') return 'a PM’s own lead';
  if (isEmergency(l)) return 'emergency / mitigation';
  if (dueSoon(l, holdUntil(now))) return 'the bid is due before the hold ends';
  return '';
}
function holdFor(pick, now){
  var t = typeof now === 'number' ? now : Date.now();
  return { state: 'held', name: s(pick.name), email: low(pick.email), field: pick.field === 'estimator' ? 'estimator' : 'pm', label: s(pick.label), k: s(pick.k), until: holdUntil(t), at: new Date(t).toISOString() };
}
/* the fields that assign a held lead to its suggested person (the deadline passed, or an admin approved) */
function releaseFields(l, how, by, now){
  var h = l.hold || {}, at = new Date(typeof now === 'number' ? now : Date.now()).toISOString(), o = {};
  o[h.field === 'estimator' ? 'estimator' : 'pm'] = h.name; o[(h.field === 'estimator' ? 'estimator' : 'pm') + 'Email'] = h.email;
  o.assignedAt = at; o.leadRole = h.k || l.leadRole || '';
  if (how === 'approved') { o.assignedBy = s(by) || 'Admin'; o.assignConfirmed = true; }
  else { o.assignedBy = 'Auto · ' + (h.label || 'lead role') + ' (held until ' + whenLabel(h.until, Date.parse(h.until)).replace(/ today$/, '') + ', nobody changed it)'; o.autoAssignedAt = at; }
  o.hold = Object.assign({}, h, { state: how === 'approved' ? 'approved' : 'auto', doneAt: at, doneBy: s(by) || (how === 'approved' ? '' : 'auto') });
  return o;
}
/* the server's run (bid-alerts, every 10 minutes): which Lead Inbox items to assign now, and which to let go
   (the CRM copy was assigned by a person meanwhile). crmLeads = gc_kv "leads" (read only). */
function dueItems(items, crmLeads, now){
  var t = typeof now === 'number' ? now : Date.now(), byInbox = {};
  arr(crmLeads).forEach(function(l){ if (l && l.inboxId && (!byInbox[l.inboxId] || s(l.id) === 'LEADIN-' + s(l.inboxId).replace(/^LI-/, ''))) byInbox[l.inboxId] = l; });   /* patch LEADFIX-1b: the item's own lead wins */
  var assign = [], drop = [], crmOnly = [];
  arr(items).forEach(function(it){
    if (!it || !it.hold || it.hold.state !== 'held') return;
    if (assignee(it) || /^(dismissed|merged)$/.test(s(it.status))) { drop.push({ id: it.id, why: assignee(it) ? 'assigned' : s(it.status) }); return; }
    var c = byInbox[it.id];
    if (c && (assignee(c) || (c.hold && c.hold.state && c.hold.state !== 'held'))) { drop.push({ id: it.id, why: 'changed in the CRM', crm: c }); return; }
    if (Date.parse(it.hold.until) <= t) assign.push(it);
  });
  /* a lead the CRM held itself (no Lead Inbox item, e.g. Roof Ignite): the notice goes out from here, the CRM writes it */
  arr(crmLeads).forEach(function(l){ if (l && !l.inboxId && isDue(l, t) && !l.deleted && !l._deleted) crmOnly.push(l); });
  return { assign: assign, drop: drop, crmOnly: crmOnly };
}

var API = { V: 1, TZ: TZ, ct: ct, ctMs: ctMs, holdUntil: holdUntil, whenLabel: whenLabel, isEmergency: isEmergency, dueSoon: dueSoon, assignee: assignee, isHeld: isHeld, isDue: isDue,
  companyWhy: companyWhy, ccWhy: ccWhy, personKind: personKind, normAddr: normAddr, earlierCompany: earlierCompany, decideSource: decideSource, storedSource: storedSource,
  ownFields: ownFields, companyFields: companyFields, noHoldWhy: noHoldWhy, holdFor: holdFor, releaseFields: releaseFields, dueItems: dueItems };
if (typeof module !== 'undefined' && module.exports) module.exports = API;
else root._gcLeadHoldCore = API;
})(this);
